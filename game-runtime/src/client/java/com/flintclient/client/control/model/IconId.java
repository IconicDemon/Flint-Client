/**
 * Module icons by name. Each constant has a namesake in {@code render.Icon} (look it up with
 * {@code Icon.valueOf(id.name())}); the model names them here so it stays free of rendering code.
 */
public enum IconId {
	GAUGE,
	SIGNAL,
	MOUSE,
	KEYS,
	PIN,
	COMPASS,
	SHIELD,
	FLASK
}
